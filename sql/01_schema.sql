CREATE TABLE leituras_sensor (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    data_hora TIMESTAMP NOT NULL,
    umidade NUMBER(5, 2),
    ph NUMBER(4, 2),
    fosforo NUMBER(1) NOT NULL,
    potassio NUMBER(1) NOT NULL,
    bomba NUMBER(1) NOT NULL,
    origem VARCHAR2(30) NOT NULL,
    criado_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_leituras_sensor PRIMARY KEY (id),
    CONSTRAINT ck_leituras_umidade CHECK (umidade IS NULL OR (umidade >= 0 AND umidade <= 100)),
    CONSTRAINT ck_leituras_ph CHECK (ph IS NULL OR (ph >= 0 AND ph <= 14)),
    CONSTRAINT ck_leituras_fosforo CHECK (fosforo IN (0, 1)),
    CONSTRAINT ck_leituras_potassio CHECK (potassio IN (0, 1)),
    CONSTRAINT ck_leituras_bomba CHECK (bomba IN (0, 1))
);

CREATE INDEX ix_leituras_sensor_data
    ON leituras_sensor (data_hora);
